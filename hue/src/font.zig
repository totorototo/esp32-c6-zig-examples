//! Minimal 5x7 font, defined as pixel art and turned into column bytes at comptime.
//! Covers space, digits, A-Z (lowercase is drawn as uppercase) and `: . - / % ! ' ( ) _ + < > , ? & "`.
//! Unknown characters render as a hollow box. UTF-8 text goes through `Chars`, which folds
//! accented Latin letters to their base letter (É -> E) so French names stay readable.

pub const width = 5;
pub const height = 7;

/// One byte per column, bit 0 = top row.
pub const Glyph = [width]u8;

pub fn glyph(c: u8) Glyph {
    const upper = if (c >= 'a' and c <= 'z') c - 32 else c;
    return table[upper];
}

const table: [256]Glyph = blk: {
    @setEvalBranchQuota(20_000);
    var t: [256]Glyph = @splat(compile(.{ "#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####" }));
    for (art) |entry| t[entry[0]] = compile(entry[1]);
    break :blk t;
};

fn compile(rows: [height]*const [width]u8) Glyph {
    var g: Glyph = @splat(0);
    for (rows, 0..) |row, r| {
        for (row, 0..) |px, col| {
            if (px == '#') g[col] |= 1 << r;
        }
    }
    return g;
}

