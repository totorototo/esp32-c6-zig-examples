//! Blinks the on-board RGB LED of an ESP32-C6-DevKitC-1 (a WS2812 on GPIO8),
//! and logs over the USB-Serial-JTAG port.
const std = @import("std");
const microzig = @import("microzig");
const hal = microzig.hal;
const gpio = hal.gpio;
const WS2812 = microzig.drivers.led.WS2812;
const Color = microzig.drivers.led.ws2812.Color;

pub const panic = microzig.panic;

pub const std_options = microzig.std_options(.{
    .logFn = hal.usb_serial_jtag.logger.log,
});

comptime {
    _ = microzig.export_startup();
}

const led_pin = gpio.num(8);
const spi_bus = hal.spi.instance.SPI2;

const colors = [_]Color{
    .{ .r = 16, .g = 0, .b = 0 },
    .{ .r = 0, .g = 16, .b = 0 },
    .{ .r = 0, .g = 0, .b = 16 },
};
const off: Color = .{ .r = 0, .g = 0, .b = 0 };

pub fn main() !void {
    // The WS2812 protocol is generated by shifting bit patterns out of SPI2's MOSI.
    led_pin.apply(.{ .output_enable = true });
    spi_bus.connect_pins(.{ .data = .{ .single_one_wire = led_pin } });
    spi_bus.apply(.{
        .clock_config = hal.clock_config,
        .baud_rate = 3_000_000,
        .bit_order = .msb_first,
    });

    const spi_dev: hal.drivers.SPI_Device = .init(spi_bus, .single_one_wire, null);
    var led: WS2812(.{
        .max_led_count = 1,
        .DatagramDevice = hal.drivers.SPI_Device,
    }) = .init(spi_dev, hal.drivers.clock_device());

    std.log.info("blinky on ESP32-C6, cpu clock {} MHz", .{hal.clock_config.cpu_clk_freq / 1_000_000});

    var i: usize = 0;
    while (true) : (i += 1) {
        const color = colors[i % colors.len];
        try led.write(&.{color});
        std.log.info("blink {}", .{i});
        hal.time.sleep_ms(500);

        try led.write(&.{off});
        hal.time.sleep_ms(500);
    }
}
