//! weblight: control the ESP32-C6-DevKitC-1 RGB LED (WS2812 on GPIO8) from a browser.
//!
//! Joins Wi-Fi (`-Dssid=... -Dpassword=...`, default `Wokwi-GUEST`), then serves on port 80:
//!   GET  /                         the control page
//!   GET  /state                    {"on":true,"r":255,"g":128,"b":0}
//!   POST /set?on=1&r=255&g=128&b=0 apply (any subset of the parameters), returns the state
//! Logs go to UART0 (115200 baud), so they show up in the Wokwi serial monitor.
const std = @import("std");
const microzig = @import("microzig");
const net = @import("net.zig");
const lwip = net.lwip;

const hal = microzig.hal;
const gpio = hal.gpio;
const rtos = hal.rtos;
const radio = hal.radio;
const WS2812 = microzig.drivers.led.WS2812;
const Color = microzig.drivers.led.ws2812.Color;

comptime {
    _ = net.exports;
    _ = microzig.export_startup();
}

pub const panic = microzig.panic;

pub const std_options = microzig.std_options(.{
    .log_level = .info,
    .log_scope_levels = &.{
        .{ .scope = .esp_radio, .level = .err },
        .{ .scope = .esp_radio_timer, .level = .err },
        .{ .scope = .esp_radio_wifi, .level = .err },
        .{ .scope = .esp_radio_osi, .level = .err },
    },
    .logFn = uart_log,
});

pub const microzig_options: microzig.Options = .{
    .interrupts = .{
        .interrupt30 = radio.interrupt_handler,
        .interrupt31 = rtos.interrupt_handler,
    },
    .cpu = .{ .interrupt_stack = .{ .enable = true, .size = 8192 } },
    .hal = .{
        .rtos = .{ .enable = true },
        .radio = .{ .wifi = .{ .on_packet_received = net.on_packet_received } },
    },
};

// Several RTOS tasks log (Wi-Fi driver, lwIP, main), so the shared line buffer needs a lock.
var log_mutex: rtos.Mutex = .{};
var log_buf: [256]u8 = undefined;

fn uart_log(
    comptime level: std.log.Level,
    comptime scope: @TypeOf(.EnumLiteral),
    comptime format: []const u8,
    args: anytype,
) void {
    log_mutex.lock();
    defer log_mutex.unlock();
    const prefix = comptime "[" ++ level.asText() ++ "] " ++ (if (scope == .default) "" else "(" ++ @tagName(scope) ++ ") ");
    const line = std.fmt.bufPrint(&log_buf, prefix ++ format ++ "\r\n", args) catch return;
    hal.uart.write(0, line);
}

const http_port = 80;

const Led = WS2812(.{ .max_led_count = 1, .DatagramDevice = hal.drivers.SPI_Device });

const State = struct {
    on: bool = true,
    color: Color = .{ .r = 255, .g = 96, .b = 0 },
};

var led: Led = undefined;
var state: State = .{};

pub fn main() !void {
    std.log.info("weblight on ESP32-C6, cpu clock {} MHz", .{hal.clock_config.cpu_clk_freq / 1_000_000});
    init_led();
    try apply_state();

    var heap: microzig.Allocator = try .init_with_heap(16384);
    try net.up(heap.allocator());

    const server = lwip.c.netconn_new_with_proto_and_callback(lwip.c.NETCONN_TCP, 0, null) orelse
        return error.NetconnAllocFailed;
    try lwip.c_err(lwip.c.netconn_bind(server, null, http_port));
    try lwip.c_err(lwip.c.netconn_listen(server));
    std.log.info("open http://{f}:{}/", .{ net.ip(), http_port });

    while (true) {
        var client: ?*lwip.c.netconn = null;
        lwip.c_err(lwip.c.netconn_accept(server, &client)) catch |err| {
            std.log.err("accept failed: {t}", .{err});
            rtos.sleep(.from_ms(100));
            continue;
        };
        serve(client.?) catch |err| std.log.warn("request failed: {t}", .{err});
        _ = lwip.c.netconn_close(client);
        _ = lwip.c.netconn_delete(client);
    }
}

fn init_led() void {
    // WS2812 bits are generated by shifting patterns out of SPI2's MOSI (see blinky).
    const pin = gpio.num(8);
    const spi = hal.spi.instance.SPI2;
    pin.apply(.{ .output_enable = true });
    spi.connect_pins(.{ .data = .{ .single_one_wire = pin } });
    spi.apply(.{ .clock_config = hal.clock_config, .baud_rate = 3_000_000, .bit_order = .msb_first });
    led = .init(.init(spi, .single_one_wire, null), hal.drivers.clock_device());
}

fn apply_state() !void {
    try led.write(&.{if (state.on) state.color else .{ .r = 0, .g = 0, .b = 0 }});
}

// ---- HTTP ----

const Request = struct {
    method: []const u8,
    path: []const u8,
    query: []const u8,
};

fn serve(conn: *lwip.c.netconn) !void {
    // Without this a browser that opens a speculative connection and sends nothing would
    // block the (single-threaded) server.
    conn.recv_timeout = 3000;

    var buf: [1024]u8 = undefined;
    const head = try read_head(conn, &buf);
    const req = parse_request_line(head) orelse return respond(conn, "400 Bad Request", "text/plain", "bad request\n");
    std.log.info("{s} {s}{s}{s}", .{ req.method, req.path, if (req.query.len > 0) "?" else "", req.query });

    if (std.mem.eql(u8, req.path, "/")) {
        if (!std.mem.eql(u8, req.method, "GET")) return respond(conn, "405 Method Not Allowed", "text/plain", "GET only\n");
        return respond(conn, "200 OK", "text/html; charset=utf-8", page);
    }
    if (std.mem.eql(u8, req.path, "/state")) {
        return respond_state(conn);
    }
    if (std.mem.eql(u8, req.path, "/set")) {
        if (!std.mem.eql(u8, req.method, "POST")) return respond(conn, "405 Method Not Allowed", "text/plain", "POST only\n");
        update_state(req.query) catch return respond(conn, "400 Bad Request", "text/plain", "bad parameter\n");
        try apply_state();
        return respond_state(conn);
    }
    return respond(conn, "404 Not Found", "text/plain", "not found\n");
}

/// Reads until the end of the request headers. The request body, if any, is ignored.
fn read_head(conn: *lwip.c.netconn, buf: []u8) ![]const u8 {
    var len: usize = 0;
    while (std.mem.indexOf(u8, buf[0..len], "\r\n\r\n") == null) {
        if (len == buf.len) return error.RequestTooLarge;

        var nb: ?*lwip.c.netbuf = null;
        try lwip.c_err(lwip.c.netconn_recv(conn, &nb));
        defer lwip.c.netbuf_delete(nb);

        // A netbuf can be a chain of fragments.
        while (true) {
            var ptr: ?*anyopaque = null;
            var n: u16 = 0;
            try lwip.c_err(lwip.c.netbuf_data(nb, &ptr, &n));
            const chunk = @as([*]const u8, @ptrCast(ptr))[0..n];
            const take = @min(chunk.len, buf.len - len);
            @memcpy(buf[len..][0..take], chunk[0..take]);
            len += take;
            if (lwip.c.netbuf_next(nb) < 0) break;
        }
    }
    return buf[0..len];
}

fn parse_request_line(head: []const u8) ?Request {
    const line_end = std.mem.indexOf(u8, head, "\r\n") orelse return null;
    var it = std.mem.tokenizeScalar(u8, head[0..line_end], ' ');
    const method = it.next() orelse return null;
    const target = it.next() orelse return null;
    const q = std.mem.indexOfScalar(u8, target, '?');
    return .{
        .method = method,
        .path = target[0 .. q orelse target.len],
        .query = if (q) |i| target[i + 1 ..] else "",
    };
}

fn update_state(query: []const u8) !void {
    var next = state;
    var it = std.mem.tokenizeScalar(u8, query, '&');
    while (it.next()) |pair| {
        const eq = std.mem.indexOfScalar(u8, pair, '=') orelse return error.BadParameter;
        const key = pair[0..eq];
        const value = try std.fmt.parseInt(u8, pair[eq + 1 ..], 10);
        if (std.mem.eql(u8, key, "on")) {
            next.on = value != 0;
        } else if (std.mem.eql(u8, key, "r")) {
            next.color.r = value;
        } else if (std.mem.eql(u8, key, "g")) {
            next.color.g = value;
        } else if (std.mem.eql(u8, key, "b")) {
            next.color.b = value;
        } else return error.BadParameter;
    }
    state = next;
}

fn respond_state(conn: *lwip.c.netconn) !void {
    var body: [64]u8 = undefined;
    const json = try std.fmt.bufPrint(&body, "{{\"on\":{},\"r\":{},\"g\":{},\"b\":{}}}", .{
        state.on, state.color.r, state.color.g, state.color.b,
    });
    return respond(conn, "200 OK", "application/json", json);
}

fn respond(conn: *lwip.c.netconn, status: []const u8, content_type: []const u8, body: []const u8) !void {
    var head: [160]u8 = undefined;
    const header = try std.fmt.bufPrint(&head, "HTTP/1.1 {s}\r\nContent-Type: {s}\r\nContent-Length: {}\r\nCache-Control: no-store\r\nConnection: close\r\n\r\n", .{ status, content_type, body.len });
    try write_all(conn, header);
    try write_all(conn, body);
}

fn write_all(conn: *lwip.c.netconn, bytes: []const u8) !void {
    try lwip.c_err(lwip.c.netconn_write_partly(conn, bytes.ptr, bytes.len, lwip.c.NETCONN_COPY, null));
}

